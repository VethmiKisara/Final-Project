    disp = ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=target_names)
    plt.figure(figsize=(6,6))
    disp.plot(values_format="d", cmap="Blues")
    plt.title(f"Confusion Matrix (Test) - {title}")
    plt.grid(False)
    plt.show()

    return acc, cm

